const LOWER_SET = new Set(CALCULATOR_BUILTIN_WORDS.map((w) => w.toLowerCase()));

/** 是否与引擎 isBuiltinWord 语义一致 */
export function isCalculatorBuiltinWord(word: string): boolean {
  if (!word) return false;
  return LOWER_SET.has(word.toLowerCase());
}
