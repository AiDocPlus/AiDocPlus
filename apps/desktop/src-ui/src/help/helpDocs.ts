/** 获取所有文档（扁平列表） */
export function getAllDocs(): HelpDoc[] {
  return HELP_CATEGORIES.flatMap(c => c.docs);
}

/** 根据 ID 获取文档 */
export function getDocById(id: string): HelpDoc | undefined {
  return getAllDocs().find(d => d.id === id);
}

/** 生成全局目录摘要（用于 AI 上下文） */
export function generateDocIndex(): string {
  return HELP_CATEGORIES.map(cat =>
    `## ${cat.icon} ${cat.title}\n` +
    cat.docs.map(d => `- ${d.title}`).join('\n')
  ).join('\n\n');
}
